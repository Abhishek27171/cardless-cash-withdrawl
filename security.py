# Server Secret Key for HMAC signature
SECRET_KEY = "cardless_atm_super_secret_btech_project_key_2026"
QR_VALIDITY_SECONDS = 60  # Configurable between 60 to 120 seconds
MAX_QR_ATTEMPTS = 3       # Max 3 QR code generation attempts per session

# ----------------- PIN SECURITY -----------------
def hash_pin(pin: str) -> str:
    """Hashes a 4-digit PIN using SHA-256 with a project salt."""
    salted = f"{pin}:{SECRET_KEY[:16]}".encode("utf-8")
    return hashlib.sha256(salted).hexdigest()

def verify_pin(plain_pin: str, hashed_pin: str) -> bool:
    """Verifies that the entered PIN matches the stored hash."""
    return hash_pin(plain_pin) == hashed_pin

# ----------------- DYNAMIC QR GENERATOR & VALIDATOR -----------------
def generate_qr_payload(session_id: str, atm_code: str, amount: float, attempts_count: int, validity_seconds: int = QR_VALIDITY_SECONDS) -> dict:
    """
    Generates a secure dynamic QR payload with a nonce and expiration timestamp.
    """
    now = time.time()
    expires_at = now + validity_seconds
    nonce = secrets.token_hex(8)

    # Data to sign
    data_str = f"{session_id}|{atm_code}|{amount:.2f}|{expires_at:.0f}|{nonce}|{attempts_count}"
    signature = hmac.new(SECRET_KEY.encode(), data_str.encode(), hashlib.sha256).hexdigest()

    payload = {
        "session_id": session_id,
        "atm_code": atm_code,
        "amount": amount,
        "nonce": nonce,
        "attempts_count": attempts_count,
        "expires_at": expires_at,
        "validity_seconds": validity_seconds,
        "signature": signature
    }
    return payload

def generate_qr_base64_image(payload: dict) -> str:
    """
    Generates a PNG QR code image as a base64 Data URL.
    """
    # Compact payload for QR scanning
    qr_data = json.dumps({
        "sid": payload["session_id"],
        "atm": payload["atm_code"],
        "amt": payload["amount"],
        "exp": int(payload["expires_at"]),
        "sig": payload["signature"]
    })

    qr = qrcode.QRCode(
        version=1,
        error_correction=qrcode.constants.ERROR_CORRECT_M,
        box_size=8,
        border=3,
    )
    qr.add_data(qr_data)
    qr.make(fit=True)

    img = qr.make_image(fill_color="#1E293B", back_color="#FFFFFF")
    buffered = io.BytesIO()
    img.save(buffered, format="PNG")
    img_b64 = base64.b64encode(buffered.getvalue()).decode("utf-8")
    return f"data:image/png;base64,{img_b64}"

def verify_qr_signature(payload: dict) -> bool:
    """
    Verifies that the QR code payload was generated by this server and hasn't been tampered with.
    """
    try:
        session_id = payload["session_id"]
        atm_code = payload["atm_code"]
        amount = float(payload["amount"])
        expires_at = float(payload["expires_at"])
        nonce = payload["nonce"]
        attempts_count = int(payload["attempts_count"])
        expected_sig = payload["signature"]

        data_str = f"{session_id}|{atm_code}|{amount:.2f}|{expires_at:.0f}|{nonce}|{attempts_count}"
        calc_sig = hmac.new(SECRET_KEY.encode(), data_str.encode(), hashlib.sha256).hexdigest()

        return hmac.compare_digest(calc_sig, expected_sig)
    except Exception:
        return False

# ----------------- FACE RECOGNITION BIOMETRICS (OPENCV) -----------------
# Load Haar cascade classifier for face detection
HAAR_CASCADE_PATH = os.path.join(cv2.data.haarcascades, "haarcascade_frontalface_default.xml")
face_cascade = cv2.CascadeClassifier(HAAR_CASCADE_PATH)

def decode_base64_image(b64_string: str) -> Optional[np.ndarray]:
    """Decodes a base64 image (data URL or raw base64) into an OpenCV BGR image."""
    try:
        if "," in b64_string:
            b64_string = b64_string.split(",", 1)[1]
        img_bytes = base64.b64decode(b64_string)
        nparr = np.frombuffer(img_bytes, np.uint8)
        img = cv2.imdecode(nparr, cv2.IMREAD_COLOR)
        return img
    except Exception:
        return None

def extract_face_crop(img: np.ndarray, target_size=(120, 120)) -> Tuple[bool, Optional[np.ndarray], str]:
    """
    Detects face in the image, crops it, converts to grayscale and normalizes it.
    Returns: (success: bool, cropped_face: np.ndarray, message: str)
    """
    if img is None:
        return False, None, "Invalid image data."

    gray = cv2.cvtColor(img, cv2.COLOR_BGR2GRAY)
    faces = face_cascade.detectMultiScale(gray, scaleFactor=1.1, minNeighbors=5, minSize=(60, 60))

    if len(faces) == 0:
        return False, None, "No face detected in image. Please ensure good lighting and face the camera directly."

    # Pick the largest detected face
    (x, y, w, h) = max(faces, key=lambda rect: rect[2] * rect[3])
    face_roi = gray[y:y+h, x:x+w]

    # Preprocess: equalize histogram to balance lighting and resize to target_size
    face_eq = cv2.equalizeHist(face_roi)
    face_resized = cv2.resize(face_eq, target_size, interpolation=cv2.INTER_AREA)

    return True, face_resized, "Face detected successfully."

def compare_faces(ref_b64: str, live_b64: str, threshold: float = 0.55) -> Tuple[bool, float, str]:
    """
    Compares reference face with live captured face using normalized correlation and histogram similarity.
    Returns: (is_match: bool, similarity_score: float, status_message: str)
    """
    ref_img = decode_base64_image(ref_b64)
    live_img = decode_base64_image(live_b64)

    if ref_img is None:
        return False, 0.0, "Reference profile photo could not be read."
    if live_img is None:
        return False, 0.0, "Live selfie camera photo could not be read."

    # Extract faces
    ok_ref, ref_face, msg_ref = extract_face_crop(ref_img)
    if not ok_ref:
        return False, 0.0, f"Profile reference face error: {msg_ref}"

    ok_live, live_face, msg_live = extract_face_crop(live_img)
    if not ok_live:
        return False, 0.0, f"Live verification error: {msg_live}"

    # Metric 1: Template Matching (Normalized Cross-Correlation)
    res_corr = cv2.matchTemplate(live_face, ref_face, cv2.TM_CCOEFF_NORMED)
    corr_score = float(res_corr[0][0])  # [-1.0, 1.0]

    # Metric 2: Histogram correlation
    hist_ref = cv2.calcHist([ref_face], [0], None, [64], [0, 256])
    hist_live = cv2.calcHist([live_face], [0], None, [64], [0, 256])
    cv2.normalize(hist_ref, hist_ref, 0, 1, cv2.NORM_MINMAX)
    cv2.normalize(hist_live, hist_live, 0, 1, cv2.NORM_MINMAX)
    hist_score = float(cv2.compareHist(hist_ref, hist_live, cv2.HISTCMP_CORREL))

    # Combined composite similarity score (0.0 to 1.0)
    composite_score = max(0.0, (corr_score * 0.6 + hist_score * 0.4))

    is_match = composite_score >= threshold
    msg = f"Match verified! (Confidence: {composite_score * 100:.1f}%)" if is_match else f"Face mismatch. Similarity score {composite_score * 100:.1f}% below threshold {threshold * 100:.0f}%."

    return is_match, composite_score, msg

